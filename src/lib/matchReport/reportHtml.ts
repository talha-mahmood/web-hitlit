// Shared HTML building blocks for every sport's "Match Report" PDF — one
// consistent look (teal headings, light-gray rounded cards) built once here
// instead of duplicated per sport. Each sport's own report module only
// supplies the content between <body> and the closing tags below.

export function escapeHtml(value: string | number): string {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

const TEAL = "#0F8A8A";
const INK = "#1F2937";
const MUTED = "#6B7280";
const CARD_BG = "#F3F4F6";

export const REPORT_STYLES = `
  * { box-sizing: border-box; }
  body {
    font-family: -apple-system, Helvetica, Arial, sans-serif;
    color: ${INK};
    margin: 0;
    padding: 32px 36px;
    font-size: 13px;
  }
  h1 {
    color: ${TEAL};
    font-size: 26px;
    margin: 0 0 16px 0;
  }
  h2 {
    color: ${TEAL};
    font-size: 15px;
    margin: 22px 0 10px 0;
  }
  .card {
    background: ${CARD_BG};
    border-radius: 14px;
    padding: 16px 18px;
  }
  .muted { color: ${MUTED}; }
  .label {
    color: ${TEAL};
    font-size: 11px;
    font-weight: 600;
    margin-bottom: 2px;
  }
  .value { font-size: 14px; font-weight: 600; }
  table { width: 100%; border-collapse: collapse; }
  .foot {
    margin-top: 28px;
    padding-top: 12px;
    border-top: 1px solid #E5E7EB;
    display: flex;
    justify-content: space-between;
    font-size: 10px;
    color: ${MUTED};
  }
  .page-break { page-break-before: always; }
`;

// The footer every page of the STUMPS-style reference PDF carries — kept as
// its own generic line here ("created from <app name>") rather than copying
// that specific third-party product's own name/branding.
export function reportFooter(appName: string): string {
  return `
    <div class="foot">
      <span>Generated by ${escapeHtml(appName)}</span>
      <span>Match Report created from <strong>${escapeHtml(appName)}</strong></span>
    </div>
  `;
}

export function wrapReportHtml(bodyHtml: string): string {
  return `<!DOCTYPE html>
<html>
  <head>
    <meta charset="utf-8" />
    <style>${REPORT_STYLES}</style>
  </head>
  <body>
    ${bodyHtml}
  </body>
</html>`;
}
