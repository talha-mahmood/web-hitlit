// Generates src/components/icons/registry.generated.ts — the set of Ionicons
// (react-icons/io5) and MaterialCommunityIcons (@mdi/js) glyphs the app and
// the website actually reference, keyed by the same kebab-case names the
// mobile app passes to <Ionicons name=…> / <MaterialCommunityIcons name=…>.
//
// Names are often dynamic (maps like sportIcons.ts, ternaries), so instead of
// parsing JSX this collects every string literal from files that use an icon
// set and keeps the ones that are real glyph names. Only those get imported,
// keeping the bundle tree-shaken.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const WEB = path.resolve(here, "..");
const ROOTS = [path.resolve(WEB, "../src"), path.resolve(WEB, "src")];
const OUT = path.resolve(WEB, "src/components/icons/registry.generated.ts");

const io5 = require("react-icons/io5");
const mdi = require("@mdi/js");

const pascal = (kebab) =>
  kebab
    .split("-")
    .map((p) => (p ? p[0].toUpperCase() + p.slice(1) : ""))
    .join("");

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === "__tests__") continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.(tsx?|jsx?)$/.test(entry.name) && !entry.name.endsWith(".generated.ts")) out.push(full);
  }
  return out;
}

const ion = new Map();
const mc = new Map();
const literal = /["'`]([a-z0-9]+(?:-[a-z0-9]+)*)["'`]/g;

for (const file of ROOTS.flatMap((r) => walk(r))) {
  const src = fs.readFileSync(file, "utf8");
  // Content files (the user guide) name Ionicons as plain data.
  const usesIon = /Ionicons|Ionicon\b|IonName/.test(src) || /[\\/]content[\\/]/.test(file);
  const usesMc = /MaterialCommunityIcons|MCIcon|McName|getSportIcon|getAmenityIcon|AMENITY_OPTIONS/.test(src);
  if (!usesIon && !usesMc) continue;
  for (const [, name] of src.matchAll(literal)) {
    if (usesIon) {
      const exp = "Io" + pascal(name);
      if (io5[exp]) ion.set(name, exp);
    }
    if (usesMc) {
      const exp = "mdi" + pascal(name);
      if (typeof mdi[exp] === "string") mc.set(name, exp);
    }
  }
}

const ionEntries = [...ion].sort(([a], [b]) => a.localeCompare(b));
const mcEntries = [...mc].sort(([a], [b]) => a.localeCompare(b));

const out = `// AUTO-GENERATED by scripts/gen-icons.mjs — do not edit. Run \`npm run icons\`.
import type { IconType } from "react-icons";
import {
${[...new Set(ionEntries.map(([, e]) => e))].map((e) => `  ${e},`).join("\n")}
} from "react-icons/io5";
import {
${[...new Set(mcEntries.map(([, e]) => e))].map((e) => `  ${e},`).join("\n")}
} from "@mdi/js";

export const ION: Record<string, IconType> = {
${ionEntries.map(([n, e]) => `  ${JSON.stringify(n)}: ${e},`).join("\n")}
};

export const MDI: Record<string, string> = {
${mcEntries.map(([n, e]) => `  ${JSON.stringify(n)}: ${e},`).join("\n")}
};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`icons: ${ionEntries.length} Ionicons, ${mcEntries.length} MaterialCommunityIcons`);
